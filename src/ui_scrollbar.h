/*
 * ============================================================
 * ui_scrollbar.h
 * ============================================================
 * شريط التمرير الموحد لكل لوحات المحرك (الخصائص، شجرة العقد، شجرة
 * الملفات...). كل لوحة تحتفظ بمتغيرين خاصين بها (مقدار التمرير
 * الحالي وهل الشريط يُسحب الآن) وتمررهما لهذي الدوال، بدل ما تكتب
 * منطق التمرير من الصفر.
 *   - عجلة الماوس فوق اللوحة: تمرير بمقدار wheel_step بكسل لكل نقرة.
 *   - سحب الشريط بالزر الأيسر للماوس.
 * ============================================================
 */

#ifndef UI_SCROLLBAR_H
#define UI_SCROLLBAR_H

#define UI_SCROLLBAR_WIDTH 8

/* يُستدعى كل إطار من دالة update اللوحة.
 *   scroll_offset: مقدار التمرير الحالي بالبكسل (يُعدَّل)
 *   dragging:      1 لو الشريط يُسحب الآن (يُعدَّل)
 *   x, w:          موضع وعرض اللوحة (الشريط ملاصق لحافتها اليمنى)
 *   viewport_y/h:  بداية وارتفاع منطقة القائمة المرئية
 *   content_h:     الارتفاع الكامل لكل الصفوف
 *   wheel_step:    بكسلات كل نقرة عجلة (عادة ارتفاع الصف) */
void ui_scrollbar_update(int *scroll_offset, int *dragging,
                          int x, int w, int viewport_y, int viewport_h,
                          int content_h, int wheel_step);

/* يرسم الشريط (الخلفية + المقبض) - يُستدعى من دالة draw اللوحة
 * بعد رسم كل الصفوف */
void ui_scrollbar_draw(int scroll_offset, int x, int w,
                        int viewport_y, int viewport_h, int content_h);

#endif /* UI_SCROLLBAR_H */
