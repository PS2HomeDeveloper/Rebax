/*
 * ============================================================
 * text_field.h
 * ============================================================
 * خانة كتابة نص عامة (اسم مشروع، مسار، بحث، إلخ) - تدعم الكتابة
 * من لوحة المفاتيح، النسخ/اللصق/القص، التنقل بالمؤشر (يسار/يمين/
 * البداية/النهاية)، والتمرير الأفقي التلقائي لما النص يتجاوز عرض
 * الخانة (بدل ما يطفح النص خارجها).
 *
 * تُستخدم من أي مكتبة واجهة تحتاج كتابة نص (project_dialog حالياً،
 * شريط البحث مستقبلاً) بدون تكرار نفس المنطق في كل مكان.
 * ============================================================
 */

#ifndef TEXT_FIELD_H
#define TEXT_FIELD_H

#define TEXT_FIELD_MAX_LEN 256

typedef struct {
    char text[TEXT_FIELD_MAX_LEN];
    int  cursor_pos;      /* موقع المؤشر داخل النص (بعدد الأحرف) */
    int  scroll_offset;   /* بكسلات النص المخفية من اليسار (للتمرير) */
    int  focused;         /* 1 لو هذي الخانة هي اللي تستقبل الكتابة الآن */

    /* ------------------------------------------------------------
     * ذاكرة تخزين مؤقت داخلية (لا تُقرأ ولا تُعدَّل من خارج text_field.c) -
     * تمنع إعادة رسم الخلفية والنص من الصفر كل إطار، وترسمهم فقط
     * لما يتغيّر شيء فعلاً (نص جديد، أو تغيّر حجم الخانة)
     * ------------------------------------------------------------ */
    void *_cache_bg_tex;
    void *_cache_text_tex;
    char  _cache_text[TEXT_FIELD_MAX_LEN];
    int   _cache_w;
    int   _cache_h;
    int   _cache_text_w;   /* أبعاد آخر نص تم رسمه فعلياً - نتجنب إعادة قياسه كل إطار */
    int   _cache_text_h;
    int   _cache_valid;
} text_field_t;

/* يهيئ خانة فارغة */
void text_field_init(text_field_t *field);

/* يحرر أي ذاكرة تخزين مؤقت (خلفية/نص) تم إنشاؤها لهذه الخانة -
 * يُستدعى مرة واحدة عند إغلاق النافذة اللي تحتويها */
void text_field_free(text_field_t *field);

/* يستدعى كل إطار (سواء الخانة مفعّلة أو لا) - يتحقق هل المستخدم
 * ضغط داخل حدود الخانة (rect) عشان يفعّلها، ولو مفعّلة يقرأ أي
 * كتابة/تنقل/نسخ-لصق جديد من window.c ويحدّث حالتها الداخلية.
 * field_width تُستخدم لحساب التمرير الأفقي الصحيح */
void text_field_update(text_field_t *field, int x, int y, int w, int h,
                        int field_width);

/* يرسم خلفية الخانة (لون رصاصي، زوايا مدورة بسيطة عبر نفس أصل
 * صورة الزر بلون مختلف) + النص داخلها مع التمرير المحسوب، بحجم
 * خط وعائلة محددة. غير const عمداً - يحدّث ذاكرة التخزين المؤقت
 * الداخلية عند الحاجة */
void text_field_draw(text_field_t *field, int x, int y, int w, int h,
                      int font_pixel_size);

#endif /* TEXT_FIELD_H */
