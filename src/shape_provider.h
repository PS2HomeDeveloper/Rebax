/*
 * ============================================================
 * shape_provider.h
 * ============================================================
 * يوفر أشكالاً (مستطيلات بزوايا مدورة) لأي مكتبة أخرى تطلبها -
 * زر، خانة كتابة، لوحة، أو أي شيء يحتاج حواف ناعمة مستقبلاً.
 *
 * لا يعتمد على أي مورد خارجي (لا صورة، لا ملف) - الشكل يُحسب
 * رياضياً مباشرة (SDF: حقل مسافة موقّع) وقت الطلب، بأي حجم ولون
 * ودرجة نعومة زوايا يُطلَب، بجودة مثالية دائماً بغض النظر عن الحجم.
 *
 * هذا الملف الوحيد في المشروع المسؤول عن توليد أشكال بحواف ناعمة.
 * ============================================================
 */

#ifndef SHAPE_PROVIDER_H
#define SHAPE_PROVIDER_H

/* صورة بكسلات RGBA جاهزة للرسم (32 بت لكل بكسل) */
typedef struct {
    unsigned char *pixels; /* بيانات خام، طولها width * height * 4 بايت */
    int width;
    int height;
} shape_image_t;

/* ينتج مستطيلاً بزوايا مدورة، بالحجم واللون ودرجة نعومة الزوايا
 * المطلوبة (corner_radius بالبكسل - كل ما زاد كانت الزوايا أكثر
 * استدارة؛ صفر يعني زوايا حادة تماماً). لا يحتاج أي تهيئة مسبقة
 * ولا مورد خارجي - جاهز للاستخدام مباشرة من أول استدعاء.
 * الناتج تخصيص جديد في الذاكرة - يجب تحريره لاحقاً بـ
 * shape_provider_free_image بعد الانتهاء من استخدامه. */
shape_image_t shape_provider_render_rect(int width, int height, int corner_radius,
                                          unsigned char r, unsigned char g, unsigned char b);

/* يحرر الذاكرة المخصصة لصورة ناتجة من shape_provider_render_rect */
void shape_provider_free_image(shape_image_t *img);

#endif /* SHAPE_PROVIDER_H */
