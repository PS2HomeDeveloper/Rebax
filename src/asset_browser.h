/*
 * ============================================================
 * asset_browser.h
 * ============================================================
 * "مدير الملفات" العام للمحرك - نافذة منبثقة احترافية لاختيار ملف
 * أو مجلد، يستخدمها أي كود ثاني بالمحرك يحتاج هذي المهمة (خاصية
 * "استيراد صورة" بعقدة Sprite، زر "تصفح" عند إنشاء مشروع، إلخ)
 * بدون ما يكتب أي منطق تصفح ملفات بنفسه - نداء واحد وينتهي الأمر.
 *
 * ------------------------------------------------------------
 * الوضعان المتاحان لأساس التصفح (asset_browser_root_t):
 * ------------------------------------------------------------
 *   ASSET_BROWSER_ROOT_ASSETS:
 *     الجذر = مجلد Assets/ الخاص بالمشروع المفتوح حالياً
 *     (current_project.h) - يُعرض للمستخدم باسم "Assets://".
 *     لا يمكن الخروج منه للأعلى إطلاقاً؛ شريط المسار أعلى النافذة
 *     يعرض المسار الحالي ويتحدّث كل ما دخل المستخدم مجلداً جديداً،
 *     لكنه لا يقدر يرجع فوق هذا الجذر بأي شكل.
 *     هذا الوضع هو المطلوب لأي خاصية عقدة تحتاج مورداً من المشروع
 *     نفسه (صورة Sprite، ملف صوت، إلخ) - المورد يجب أن يكون داخل
 *     المشروع أصلاً حتى يصح تصديره لاحقاً مع اللعبة.
 *
 *   ASSET_BROWSER_ROOT_DEVICE:
 *     الجذر = جذر الجهاز بالكامل ("/") - بلا أي قيد. يُستخدم لأي
 *     حالة تحتاج مساراً خارج المشروع تماماً (مثال: زر "Browse"
 *     عند إنشاء مشروع جديد، لاختيار أين يُنشأ مجلد المشروع نفسه
 *     على الجهاز).
 *
 * ------------------------------------------------------------
 * وضعا الاختيار (asset_browser_mode_t):
 * ------------------------------------------------------------
 *   ASSET_BROWSER_MODE_PICK_FILE:
 *     يختار المستخدم ملفاً واحداً. مرّر قائمة امتدادات مقبولة
 *     (extensions) فتُعرض فقط الملفات المطابقة (بالإضافة للمجلدات
 *     دائماً، للتنقل بينها بحرية) - أو مرّر NULL لعرض كل الملفات
 *     بلا فلترة. الضغط على ملف يحدّده (تظليل)، وزر "Select" أسفل
 *     النافذة يؤكد الاختيار الحالي فقط.
 *
 *   ASSET_BROWSER_MODE_PICK_FOLDER:
 *     يختار المستخدم مجلداً (لا يظهر أي ملف قابل للاختيار - فقط
 *     تظهر بشكل خافت للسياق، والتنقل بينها معطَّل). المستخدم يتنقل
 *     بالمجلدات بالضغط عليها، وزر "Select" يختار المجلد المفتوح
 *     حالياً بالضبط (نفس فلسفة نوافذ اختيار المجلد المعتادة).
 *
 * ------------------------------------------------------------
 * مثال استخدام كامل (خاصية "Import Image" بعقدة Sprite مستقبلية):
 * ------------------------------------------------------------
 *   static void on_image_picked(const char *path, void *user_data) {
 *       if (path == NULL) return; // المستخدم ألغى الاختيار
 *       my_sprite_set_texture_path((my_sprite_t *)user_data, path);
 *   }
 *   ...
 *   static const char *img_exts[] = { "png", "jpg", "jpeg", "bmp" };
 *   asset_browser_open(ASSET_BROWSER_ROOT_ASSETS, ASSET_BROWSER_MODE_PICK_FILE,
 *                       img_exts, 4, on_image_picked, my_sprite_ptr);
 * ============================================================
 */

#ifndef ASSET_BROWSER_H
#define ASSET_BROWSER_H

typedef enum {
    ASSET_BROWSER_ROOT_ASSETS, /* محصور داخل Assets:// الخاصة بالمشروع المفتوح */
    ASSET_BROWSER_ROOT_DEVICE  /* جذر الجهاز بالكامل، بلا أي قيد */
} asset_browser_root_t;

typedef enum {
    ASSET_BROWSER_MODE_PICK_FILE,   /* اختيار ملف واحد (بامتدادات محددة اختيارياً) */
    ASSET_BROWSER_MODE_PICK_FOLDER, /* اختيار مجلد فقط - الملفات تُعرض للسياق بلا إمكانية اختيارها */
    ASSET_BROWSER_MODE_SAVE_FILE    /* نفس تصفح PICK_FOLDER + خانة اسم ملف قابلة للتعديل بالأسفل -
                                      * تُفتح عبر asset_browser_open_save (مو asset_browser_open) */
} asset_browser_mode_t;

/* تُستدعى مرة واحدة بالضبط عند إغلاق النافذة:
 *   picked_path: المسار الكامل المختار عند ضغط "Select"، أو NULL
 *                لو أُلغيت العملية (زر Cancel أو زر الإغلاق X) -
 *                يجب دائماً التحقق من NULL قبل استخدام المسار.
 *   user_data:   نفس المؤشر الحر اللي مرّرته لـ asset_browser_open
 *                بدون أي تعديل - استخدمه لتعرف "لأي عنصر بالضبط
 *                كان هذا الاستدعاء" لو عندك أكثر من زر يفتح
 *                المتصفح لأغراض مختلفة */
typedef void (*asset_browser_callback_t)(const char *picked_path, void *user_data);

/* يفتح نافذة متصفح الملفات باحترافية كاملة (شريط مسار، بحث، شبكة
 * أيقونات مع صور مصغّرة حقيقية للصور، زرا Cancel/Select، وزر إغلاق X).
 *
 *   root:             أساس التصفح (راجع الشرح فوق)
 *   mode:              اختيار ملف أو مجلد
 *   extensions:        مصفوفة امتدادات بدون نقطة (مثل "png", "jpg") -
 *                      تُقارن بلا حساسية لحالة الأحرف. مرّر NULL
 *                      (وextension_count = 0) لعرض كل الملفات بلا
 *                      فلترة، أو دائماً بوضع PICK_FOLDER (تُتجاهل).
 *   extension_count:   طول مصفوفة extensions
 *   callback:          دالة الرد - إلزامية عملياً (بدونها لا فائدة
 *                      من فتح النافذة أصلاً)
 *   user_data:         مؤشر حر يُمرَّر كما هو لـcallback، أو NULL
 *
 * ملاحظة: لو root=ASSETS ولم يكن هناك مشروع مفتوح حالياً
 * (current_project_is_open() == 0)، تُستدعى callback فوراً بـNULL
 * والنافذة لا تُفتح إطلاقاً - لا يوجد Assets:// بلا مشروع مفتوح */
void asset_browser_open(asset_browser_root_t root, asset_browser_mode_t mode,
                         const char **extensions, int extension_count,
                         asset_browser_callback_t callback, void *user_data);

/* نافذة "حفظ باسم" - تصفح مجلدات (بنفس سلوك PICK_FOLDER بالضبط:
 * الملفات تُعرض خافتة للسياق بلا إمكانية اختيارها) + خانة اسم ملف
 * قابلة للتعديل بأسفل النافذة، مُهيَّأة بـdefault_filename (بامتداده
 * كاملاً، مثال: "Player.rscene") - المستخدم يقدر يعدّله بحرية قبل
 * التأكيد. عنوان النافذة "Save As"، وزر التأكيد يحمل نص "Save" بدل
 * "Select". لو ضغط المستخدم "Save": تُستدعى callback بالمسار الكامل
 * = المجلد الحالي المتصفَّح + "/" + نص خانة الاسم كما هو حرفياً (بلا
 * أي تدخل أو تصحيح تلقائي للامتداد - المستخدم مسؤول عن كتابته صح،
 * الاسم الافتراضي أصلاً يوفره جاهزاً بامتداده). لو "Cancel": تُستدعى
 * بـNULL، بنفس منطق asset_browser_open تماماً */
void asset_browser_open_save(asset_browser_root_t root, const char *default_filename,
                              asset_browser_callback_t callback, void *user_data);

/* هل النافذة مفتوحة حالياً؟ - تُستخدم من الكود المستدعي (أو من
 * main.c لو أردت رسمها فوق كل شيء آخر بمستوى أعلى) لمعرفة هل
 * يحدّثها ويرسمها هذا الإطار */
int asset_browser_is_open(void);

/* يحدّث حالة النافذة (تنقل، بحث، تمرير، ضغط أزرار) - يُستدعى كل
 * إطار بعد window_poll_events مباشرة، فقط لو النافذة مفتوحة.
 * يستدعي callback المسجَّلة تلقائياً عند اختيار نهائي أو إلغاء،
 * ثم يغلق النافذة بنفسه - لا حاجة لأي كود خارجي يتحقق من النتيجة
 * بنفسه أو يغلقها يدوياً */
void asset_browser_update(int window_w, int window_h);

/* يرسم النافذة فوق كل شيء آخر - يُستدعى كل إطار بعد رسم باقي
 * الواجهة، فقط لو النافذة مفتوحة */
void asset_browser_draw(int window_w, int window_h);

/* يحرر كل الموارد الداخلية (صور مصغّرة، نصوص، أزرار) - يُستدعى
 * مرة واحدة عند إغلاق البرنامج */
void asset_browser_shutdown(void);

#endif /* ASSET_BROWSER_H */
