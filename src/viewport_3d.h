/*
 * ============================================================
 * viewport_3d.h
 * ============================================================
 * يرسم عالم التطوير الافتراضي لمشهد ثلاثي الأبعاد: كاميرا منظور
 * حقيقية (Perspective) - إسقاط فعلي بمصفوفة، لا تخطيط وهمي - تصوّر
 * شبكة أرضية عند الارتفاع صفر (مستوى X/Z) تدل على أرضية العالم،
 * ومحوري X (أحمر) وZ (أخضر) يتقاطعان بالضبط عند نقطة أصل العالم
 * (0,0,0). كاميرا "طيران" حرة (Fly Camera) - نفس فلسفة Unity/Unreal:
 * الضغط المستمر على الزر الأيمن للماوس يفعّل النظر (mouse-look) +
 * حركة WASD/QE، Shift للتسريع، عجلة الماوس أثناء ذلك تضبط سرعة
 * الطيران نفسها، وF لتأطير سريع لأصل العالم.
 * ============================================================
 */

#ifndef VIEWPORT_3D_H
#define VIEWPORT_3D_H

/* يحدّث حالة كاميرا الطيران (موضع/زوايا نظر/سرعة) بناءً على مدخلات
 * الماوس ولوحة المفاتيح هذا الإطار - يستقبل مستطيل منطقة الكاميرا
 * الحالي (x, y, w, h) بإحداثيات النافذة لأن بدء النظر بالزر الأيمن
 * لازم يبدأ من داخله فعلياً (بعدها يستمر حتى لو خرج المؤشر مؤقتاً،
 * نفس سلوك سحب الحدود الفاصلة بالمكان الثاني). يُستدعى مرة كل إطار
 * من editor_workspace_update وقت كاميرا 3D فعّالة، قبل الرسم */
void viewport_3d_update(int x, int y, int w, int h);

/* يرسم عالم التطوير 3D كاملاً داخل مستطيل منطقة الكاميرا
 * (x, y, w, h) بإحداثيات النافذة - يُستدعى كل إطار من
 * editor_workspace_draw وقت اختيار كاميرا 3D */
void viewport_3d_draw(int x, int y, int w, int h);

/* يسقط نقطة بفضاء عالم المشهد 3D لإحداثيات شاشة فعلية داخل مستطيل
 * الكاميرا الحالي (cam_x, cam_y, cam_w, cam_h)، عبر نفس كاميرا
 * المنظور اللي ترسم بيها الشبكة بالضبط - نقطة الدخول النظيفة لأي
 * عقدة (Element3D أو أي نوع مستقبلي يرث منها) تحتاج ترسم نفسها
 * بمكانها الصحيح بمنطقة الكاميرا، بدل ما تكرر رياضيات الإسقاط
 * بنفسها. يرجع 1 لو النقطة أمام الكاميرا (قابلة للرسم فعلياً)،
 * و0 لو خلفها (لا تُرسم - النقطة المسقطة بهذي الحالة غير معرَّفة) */
int viewport_3d_project(float world_x, float world_y, float world_z,
                         int cam_x, int cam_y, int cam_w, int cam_h,
                         int *out_screen_x, int *out_screen_y);

#endif /* VIEWPORT_3D_H */
