/*
 * ============================================================
 * scene_tabs.h
 * ============================================================
 * يدير عدة مشاهد مفتوحة بالذاكرة بآن واحد (تبويبات شريط المشاهد) -
 * التبويب "النشط" حالياً هو اللي حالته حية فعلياً بـscene_tree_panel
 * وcurrent_scene (نفس ما كان الحال قبل هذا الملف). أي تبويب ثانٍ
 * غير نشط تُخزَّن حالته بمخزن مؤقت بالذاكرة (عبر
 * scene_tree_panel_serialize) - بلا أي كتابة قرص فعلية وقت التبديل
 * بين المشاهد، فقط وقت الحفظ الصريح.
 *
 * يبقى تبويب واحد ع الأقل مفتوحاً دائماً - إغلاق آخر تبويب ينشئ
 * تبويباً فاضياً ("empty") بدلاً منه فوراً.
 * ============================================================
 */

#ifndef SCENE_TABS_H
#define SCENE_TABS_H

#define SCENE_TABS_MAX 16

/* تُستدعى مرة واحدة عند بدء واجهة التطوير - تنشئ أول تبويب فاضٍ
 * ("empty") وتفعّله */
void scene_tabs_init(void);

/* عدد التبويبات المفتوحة حالياً (دائماً ≥1) */
int scene_tabs_count(void);

/* فهرس التبويب النشط حالياً (المعروض فعلياً بـscene_tree_panel/
 * properties_panel/الفيوبورت) */
int scene_tabs_active_index(void);

/* الاسم المعروض لتبويب معين (بلا حاجة يكون نشطاً حالياً) - نفس صيغة
 * current_scene_get_display_name بالضبط ("empty"، اسم أول عقدة،
 * أو اسم الملف المحفوظ) */
const char *scene_tabs_get_display_name(int index);

/* 1 لو فيه تعديلات غير محفوظة بهذا التبويب تحديداً */
int scene_tabs_get_dirty(int index);

/* ينشئ تبويب مشهد جديد فاضٍ ("empty") ويفعّله فوراً - يرفض (يرجع 0،
 * بلا أي تأثير) لو التبويب النشط الحالي أصلاً فاضٍ وبلا أي تعديل
 * (مافيه داعٍ لتبويبين فاضيين مع بعض)، أو لو وصلنا SCENE_TABS_MAX.
 * يرجع 1 لو أنشأ فعلاً */
int scene_tabs_new(void);

/* يبدّل التبويب النشط لفهرس معين - يخزّن حالة التبويب الحالي
 * بالذاكرة أولاً (serialize)، بعدها يحمّل حالة التبويب الجديد. بلا
 * أي تأثير لو index خارج المدى أو نفس التبويب النشط أصلاً */
void scene_tabs_switch_to(int index);

/* يغلق تبويب معين نهائياً فوراً - بلا أي سؤال عن الحفظ هنا (هذي
 * مسؤولية الواجهة: تعرض نافذة تأكيد الحفظ *قبل* ما تنادي هذي
 * الدالة، وتستدعي current_scene_save() أولاً بنفسها لو المستخدم
 * اختار "حفظ"). لو كان آخر تبويب متبقٍ، ينشئ تبويباً فاضياً جديداً
 * بدلاً منه فوراً (يبقى تبويب واحد ع الأقل مفتوحاً دائماً) */
void scene_tabs_close(int index);

void scene_tabs_shutdown(void);

#endif /* SCENE_TABS_H */
