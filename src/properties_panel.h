/*
 * ============================================================
 * properties_panel.h
 * ============================================================
 * يعرض خصائص العقدة المحددة حالياً بـscene_tree_panel - القيم
 * المعروضة والمعدَّلة هنا هي القيم الحقيقية الحية لنفس نسخة العقدة
 * بالمشهد (عبر scene_tree_panel_get_values)، مو نسخة عرض مؤقتة -
 * أي تعديل هنا ينعكس فوراً على نفس الذاكرة اللي الفيوبورت يرسم منها.
 * ============================================================
 */

#ifndef PROPERTIES_PANEL_H
#define PROPERTIES_PANEL_H

/* يحدّد العقدة المعروضة خصائصها الآن بفهرسها الحقيقي بشجرة المشهد
 * (مو نوعها/اسمها - فهرس فريد يقدر يميّز عقدتين بنفس الاسم) -
 * تُستدعى من scene_tree_panel عند الضغط على أي عقدة بالشجرة */
void properties_panel_set_selected(int node_index);

/* يلغي أي تحديد حالي - البانل يرجع فاضي */
void properties_panel_clear_selection(void);

/* يحدّث كل خانات تحرير القيم (كتابة، تركيز، مؤشر...) ويكتب أي قيمة
 * جديدة مباشرة على ذاكرة العقدة الحقيقية - يُستدعى كل إطار قبل
 * الرسم، حتى لو ما فيه تحديد حالياً (يرجع فوراً وقتها) */
void properties_panel_update(int x, int y, int w, int h);

void properties_panel_draw(int x, int y, int w, int h);
void properties_panel_shutdown(void);

#endif /* PROPERTIES_PANEL_H */
