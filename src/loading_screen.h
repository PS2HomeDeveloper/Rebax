#ifndef LOADING_SCREEN_H
#define LOADING_SCREEN_H

/* يُظهر الشاشة ويصفّر عداد الحركة الداخلي */
void loading_screen_show(void);

/* نفس الشاشة، لكن بلا اختفاء تلقائي بعد مدة ثابتة - تبقى ظاهرة
 * لحد ما المتصل ينادي loading_screen_hide بنفسه. تُستخدم وقت انتظار
 * عملية حقيقية متغيرة المدة (إعداد ريباكس أول تشغيل مثلاً) بدل
 * وقت وهمي ثابت */
void loading_screen_show_indefinite(void);

/* يخفي الشاشة */
void loading_screen_hide(void);

/* 1 لو الشاشة ظاهرة حالياً، 0 غير ذلك */
int loading_screen_is_visible(void);

/* يرجع 1 لمرة واحدة بس، بالضبط في الإطار اللي اختفت فيه الشاشة
 * تلقائياً (بعد المدة المؤقتة الحالية) - يُستخدم من main.c ليعرف
 * متى بالضبط ينتقل للشاشة التالية، بدون تكرار الانتقال كل إطار */
int loading_screen_just_finished(void);

/* يُستدعى مرة كل إطار (حتى لو مخفية) - يحدّث عداد الحركة الداخلي */
void loading_screen_update(void);

/* يرسم الشاشة كاملة (خلفية + مؤشر دوّار في المنتصف) - لا يرسم
 * شيئاً لو كانت مخفية حالياً */
void loading_screen_draw(int window_w, int window_h);

#endif /* LOADING_SCREEN_H */
