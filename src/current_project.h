/*
 * ============================================================
 * current_project.h
 * ============================================================
 * يخزّن مسار جذر المشروع المفتوح حالياً بذاكرة البرنامج (RAM) -
 * مو ملف على القرص، بس حالة وقت التشغيل. يُملأ مرة وحدة بعد نجاح
 * إنشاء مشروع (project_create)، وأي بانل يحتاج يعرف "وين المشروع
 * المفتوح؟" (نظام الملفات، لاحقاً حفظ/تحميل المشاهد) يسأل من هنا.
 * ============================================================
 */

#ifndef CURRENT_PROJECT_H
#define CURRENT_PROJECT_H

/* يضبط مسار جذر المشروع المفتوح حالياً (المسار الكامل لمجلد
 * المشروع نفسه، مو مجلد Assets بداخله) */
void current_project_set_path(const char *root_path);

/* يرجع مسار المشروع المفتوح حالياً، أو NULL لو ما فيه مشروع مفتوح */
const char *current_project_get_path(void);

/* يرجع 1 لو فيه مشروع مفتوح حالياً، 0 غير ذلك */
int current_project_is_open(void);

#endif /* CURRENT_PROJECT_H */
