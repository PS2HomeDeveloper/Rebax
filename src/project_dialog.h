#ifndef PROJECT_DIALOG_H
#define PROJECT_DIALOG_H

/* يفتح النافذة (تصبح مرئية وتستقبل الكتابة) */
void project_dialog_open(void);

/* هل النافذة مفتوحة حالياً؟ - تُستخدم من main.c لمعرفة هل نرسمها */
int project_dialog_is_open(void);

/* يحدّث حالة النافذة (كتابة، ضغط أزرار) - يُستدعى كل إطار بعد
 * window_poll_events مباشرة، فقط لو النافذة مفتوحة */
void project_dialog_update(int window_w, int window_h);

/* يرسم النافذة فوق كل شيء آخر - يُستدعى كل إطار بعد رسم باقي
 * الواجهة، فقط لو النافذة مفتوحة */
void project_dialog_draw(int window_w, int window_h);

/* يحرر كل الموارد الداخلية - يُستدعى مرة واحدة عند إغلاق البرنامج */
void project_dialog_shutdown(void);

#endif /* PROJECT_DIALOG_H */
