/*
 * ============================================================
 * editor_workspace.h
 * ============================================================
 * الهيكل العام لواجهة التطوير: خمس مناطق رصّ (يمين-فوق، يمين-تحت،
 * يسار-فوق، يسار-تحت، وسط-تحت) حول منطقة كاميرا مركزية، مفصولة
 * بحدود قابلة للسحب لتغيير الأحجام. لا يحتوي أي بانل فعلي بعد -
 * فقط الهيكل والألوان والتفاعل (سحب الحدود).
 * ============================================================
 */

#ifndef EDITOR_WORKSPACE_H
#define EDITOR_WORKSPACE_H

/* نوع كاميرا التطوير المعروضة حالياً بمنطقة الكاميرا الوسطى -
 * ثنائية الأبعاد (عالم مسطح، viewport_2d) أو ثلاثية الأبعاد (عالم
 * بمنظور حقيقي، viewport_3d). مستقبلاً سيُحدَّد هذا تلقائياً حسب
 * نوع المشهد المفتوح فعلياً بالمشروع - حالياً ثابت افتراضياً على
 * 3D عند فتح المحرك، قابل للتبديل يدوياً عبر
 * editor_workspace_set_camera_mode لحين وجود واجهة اختيار فعلية */
typedef enum {
    EDITOR_CAMERA_MODE_2D,
    EDITOR_CAMERA_MODE_3D
} editor_camera_mode_t;

/* يبدّل نوع الكاميرا المعروضة بمنطقة الكاميرا - يُستدعى مستقبلاً
 * من منطق اختيار/فتح نوع المشهد (لسه غير موجود) */
void editor_workspace_set_camera_mode(editor_camera_mode_t mode);

/* يحدّث حالة السحب (هل المستخدم ماسك أحد الحدود الآن) - يُستدعى
 * مرة كل إطار قبل الرسم */
void editor_workspace_update(int window_w, int window_h);

/* يرسم كامل هيكل الواجهة: المناطق الخمس + منطقة الكاميرا + الحدود
 * الفاصلة بينها */
void editor_workspace_draw(int window_w, int window_h);

/* لا موارد محمَّلة حالياً - موجودة لثبات نمط دورة الحياة */
void editor_workspace_shutdown(void);

#endif /* EDITOR_WORKSPACE_H */
