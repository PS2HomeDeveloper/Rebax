/*
 * ============================================================
 * font.h
 * ============================================================
 * مكتبة الخطوط. تحمّل ملفي الخط المضمّنين (Regular و Bold) مرة
 * واحدة فقط، وتوفر دالة عامة لأي مكتبة أخرى ترسم أي نص (جملة،
 * حرف، رقم) بأي حجم تريده، على شكل بكسلات RGBA جاهزة للرسم.
 *
 * تُستخدم من أي مكتبة واجهة (ui_project_center، إلخ) تحتاج تضع
 * نص على زر أو أيقونة أو أي مكان آخر.
 * ============================================================
 */

#ifndef FONT_H
#define FONT_H

/* وزن الخط المطلوب */
typedef enum {
    FONT_WEIGHT_REGULAR,
    FONT_WEIGHT_BOLD
} font_weight_t;

/* صورة نص جاهزة للرسم - بكسلات RGBA (النص أبيض شفاف الحواف،
 * يُلوَّن لاحقاً وقت الرسم على الشاشة حسب اللون المطلوب) */
typedef struct {
    unsigned char *pixels; /* طولها width * height * 4 بايت */
    int width;
    int height;
} font_text_image_t;

/* يحمّل ملفي الخط المضمّنين (مرة واحدة فقط). يرجع 1 عند النجاح
 * و0 عند الفشل. يجب استدعاؤه قبل أي استدعاء لـ font_render_text */
int font_init(void);

/* يرسم نص (جملة، حرف، رقم - أي سلسلة نصية) بالوزن والحجم المطلوبين
 * (pixel_size هو ارتفاع الحرف بالبكسل تقريباً، نفس مفهوم "حجم الخط"
 * المعتاد). الناتج تخصيص جديد في الذاكرة - يُحرَّر لاحقاً بـ
 * font_free_text_image بعد الانتهاء من استخدامه أو تحويله لـ texture */
font_text_image_t font_render_text(const char *text, font_weight_t weight,
                                    int pixel_size);

/* يحرر صورة نص ناتجة من font_render_text */
void font_free_text_image(font_text_image_t *img);

/* يحرر بيانات الخطوط المحمَّلة داخلياً - يُستدعى مرة واحدة عند
 * إغلاق البرنامج */
void font_shutdown(void);

#endif /* FONT_H */
