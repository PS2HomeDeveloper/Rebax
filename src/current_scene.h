/*
 * ============================================================
 * current_scene.h
 * ============================================================
 * حالة المشهد المفتوح حالياً - مسار الملف على القرص (أو بلا مسار
 * لو لسه ما اتحفظ)، وعلامة "فيه تعديلات غير محفوظة". يُبنى فوق
 * scene_tree_panel_serialize/deserialize مباشرة (نفس البيانات
 * الحقيقية، بلا أي نسخة وسيطة) - هذا الملف يضيف طبقة "أين نحفظ"
 * و"هل تغيّر شيء" فوق منطق القراءة/الكتابة الموجود أصلاً.
 *
 * نفس فلسفة current_project.h بالضبط، لمستوى المشهد بدل المشروع.
 * ============================================================
 */

#ifndef CURRENT_SCENE_H
#define CURRENT_SCENE_H

/* يهيّئ مشهداً جديداً فارغاً بالذاكرة (يمسح scene_tree_panel كاملاً)
 * - بلا مسار، بلا تعديلات. يُستدعى عند فتح واجهة التطوير لأول مرة،
 * أو عند إنشاء تبويب مشهد جديد بشريط المشاهد ("+") */
void current_scene_new(void);

/* مسار الملف الحالي على القرص - NULL لو المشهد لسه ما اتحفظ إطلاقاً
 * (مشهد جديد بالذاكرة بس) */
const char *current_scene_get_path(void);

/* هل فيه تعديلات لم تُحفظ؟ (إضافة عقدة، تعديل خاصية حقيقي...) */
int current_scene_is_dirty(void);

/* يُستدعى من أي مكان يعدّل المشهد فعلياً - يرفع علامة "غير محفوظ".
 * scene_tree_panel وproperties_panel ينادونها تلقائياً عند أي تعديل
 * حقيقي (إضافة عقدة، أو قيمة خاصية اتغيّرت فعلاً) - بلا حاجة لأي
 * كود ثانٍ يناديها يدوياً */
void current_scene_mark_dirty(void);

/* الاسم المعروض بتبويب المشهد بالشريط - "empty" لو مشهد جديد بلا
 * عقد إطلاقاً، اسم أول عقدة أُضيفت لو مشهد جديد لسه ما اتحفظ (فيه
 * محتوى)، أو اسم الملف (بلا الامتداد ولا المسار) لو محفوظ مسبقاً.
 * مؤشر صالح للاستخدام المباشر بالرسم (مو ملك المتصل، ما يُحرَّر) */
const char *current_scene_get_display_name(void);

/* يحفظ المشهد الحالي لمسار جديد صراحة - يحدّث current_scene_get_path()
 * ويصفّر علامة dirty عند النجاح. يرجّع 1 لو نجح، 0 لو فشل (مسار غير
 * قابل للكتابة، مساحة غير كافية...) */
int current_scene_save_as(const char *path);

/* يحفظ لنفس المسار الحالي (current_scene_get_path()) - يرجّع 0
 * فوراً لو المشهد لسه ما اتسمّى مسار (استخدم save_as أول مرة) */
int current_scene_save(void);

/* يحمّل مشهداً من مسار - يستبدل محتوى scene_tree_panel بالكامل
 * (نفس مسح scene_tree_panel_deserialize الداخلي)، يحدّث
 * current_scene_get_path() لهذا المسار، ويصفّر dirty عند النجاح.
 * يرجّع 1 لو نجح، 0 لو فشل (ملف غير موجود، أو محتوى غير متوافق) */
int current_scene_load(const char *path);

/* يستبدل حالة "أين نحفظ" و"هل فيه تعديل" مباشرة، بلا أي لمس لمحتوى
 * scene_tree_panel نفسه ولا للقرص إطلاقاً - تُستخدم فقط من نظام
 * تبديل تبويبات المشاهد (scene_tabs.c) وقت التبديل بين مشاهد مفتوحة
 * بالذاكرة (محتوى العقد نفسه يُنقَل بشكل منفصل تماماً عبر
 * scene_tree_panel_serialize/deserialize). path=NULL يعني "لسه ما
 * اتحفظ" */
void current_scene_restore_state(const char *path, int dirty);

#endif /* CURRENT_SCENE_H */
