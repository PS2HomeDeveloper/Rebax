/*
 * ============================================================
 * viewport_2d.h
 * ============================================================
 * يرسم عالم التطوير الافتراضي لمشهد ثنائي الأبعاد: خلفية، شبكة
 * خطوط رمادية، ومحوري X (أحمر) وY (أخضر) يتقاطعان عند نقطة أصل
 * العالم (0,0). كاميرا حرة: تحريك جانبي (Pan) بالزر الأوسط للماوس،
 * وتكبير/تصغير بعجلة الماوس مركّز على موضع المؤشر نفسه (نفس سلوك
 * Figma/Photoshop/Godot 2D - يبقى العنصر تحت المؤشر بمكانه أثناء
 * التكبير، مو مركز الشاشة).
 * ============================================================
 */

#ifndef VIEWPORT_2D_H
#define VIEWPORT_2D_H

/* يحدّث حالة كاميرا الـ2D الحرة (إزاحة Pan + مستوى تكبير Zoom)
 * بناءً على مدخلات الماوس هذا الإطار - يستقبل مستطيل منطقة الكاميرا
 * الحالي (x, y, w, h) بإحداثيات النافذة لأن بدء التحريك بالزر
 * الأوسط لازم يبدأ من داخله فعلياً. يُستدعى مرة كل إطار من
 * editor_workspace_update وقت كاميرا 2D فعّالة، قبل الرسم */
void viewport_2d_update(int x, int y, int w, int h);

/* يرسم عالم التطوير 2D كاملاً داخل مستطيل منطقة الكاميرا
 * (x, y, w, h) بإحداثيات النافذة - يُستدعى كل إطار من
 * editor_workspace_draw وقت اختيار كاميرا 2D */
void viewport_2d_draw(int x, int y, int w, int h);

/* يسقط نقطة بفضاء عالم المشهد 2D (الوحدة = بكسل، الأصل
 * بمنتصف منطقة الكاميرا) لإحداثيات شاشة فعلية داخل مستطيل الكاميرا
 * الحالي (cam_x, cam_y, cam_w, cam_h) - نقطة الدخول النظيفة لأي
 * عقدة (Element2D أو أي نوع مستقبلي يرث منها) تحتاج ترسم نفسها
 * بمكانها الصحيح بمنطقة الكاميرا، بدل ما تكرر حساب الإسقاط بنفسها */
void viewport_2d_project(float world_x, float world_y,
                          int cam_x, int cam_y, int cam_w, int cam_h,
                          int *out_screen_x, int *out_screen_y);

void viewport_2d_unproject(int screen_x, int screen_y,
                            int cam_x, int cam_y, int cam_w, int cam_h,
                            float *out_world_x, float *out_world_y);

#endif /* VIEWPORT_2D_H */
