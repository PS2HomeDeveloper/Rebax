#ifndef PS2_EXPORTER_H
#define PS2_EXPORTER_H

typedef enum {
    PS2_EXPORT_STATUS_IDLE,
    PS2_EXPORT_STATUS_RUNNING,
    PS2_EXPORT_STATUS_SUCCESS,
    PS2_EXPORT_STATUS_FAILED
} ps2_export_status_t;

/* يبدأ تصديراً جديداً. exe_name بلا امتداد (يُضاف ".elf" تلقائياً)،
 * is_release=1 يعني نزع الرموز (EE_STRIP) بعد البناء الناجح،
 * output_dir مسار مطلق للمجلد اللي يُنسخ فيه الملف التنفيذي
 * النهائي. يرجع 1 لو بدأ فعلاً، 0 لو فيه تصدير شغال أصلاً أو ما
 * فيه مشروع مفتوح حالياً (current_project_is_open() == 0) */
int ps2_export_start(const char *exe_name, int is_release, const char *output_dir);

/* يتقدّم بخطوة واحدة بعملية التصدير الجارية - يُستدعى كل إطار
 * أثناء التصدير (export_dialog_update). بلا أي حجب إطلاقاً - كل
 * قراءة من عملية فرعية غير حاجزة، فتكرار الاستدعاء هو التقدّم
 * الفعلي بالحالة */
void ps2_export_update(void);

ps2_export_status_t ps2_export_get_status(void);

/* يرجع أقدم سطر ناتج جديد لسه ما استُهلك (تسلسلياً، سطر بكل
 * استدعاء) - أو NULL لو ما فيه شيء جديد. النص المرجَّع مملوك داخلياً
 * (صالح لحد أول استدعاء تالٍ لأي دالة هنا) - المتصل ينسخه لو يحتاجه
 * بعد ذلك */
const char *ps2_export_poll_next_line(void);

/* يلغي التصدير الجاري فوراً (يقتل أي عملية فرعية شغالة حالياً عبر
 * pclose) ويعيد الحالة لـIDLE. بلا أي تأثير لو ما فيه تصدير شغال */
void ps2_export_cancel(void);

#endif /* PS2_EXPORTER_H */
